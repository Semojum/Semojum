"""Build the Nuridot Braille font: Unicode braille cells (U+2800-U+28FF) whose empty dot positions stay visible.

Raised dots are solid; empty positions are drawn small ("dots") or as thin rings ("rings") so a cell's shape reads at
a glance, the way simulated-braille fonts do. The cell is 740/1024 em wide with SimBraille's vertical metrics, so it
can replace that font without moving the editor layout. The outlines are generated here, not copied from any font.

usage: python build-braille-font.py <out.ttf> [dots|rings]
"""
import math
import sys

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

UPM, ADVANCE, ASCENT, DESCENT, LINE_GAP = 1024, 740, 890, 224, 95
RAISED = 90  # radius of a raised dot
# Six-dot cells: two columns, three rows. Eight-dot cells use four tighter rows so dots 7 and 8 stay inside the line.
COLUMNS = (232, 508)
ROWS6, ROWS8, RAISED8 = (609, 333, 57), (690, 460, 230, 0), 75
# Braille dot numbering: dots 1-3 (and 7) are the left column, 4-6 (and 8) the right, top to bottom.
DOT_POSITIONS = {1: (0, 0), 2: (0, 1), 3: (0, 2), 4: (1, 0), 5: (1, 1), 6: (1, 2), 7: (0, 3), 8: (1, 3)}


def circle(pen, cx, cy, r, clockwise=True):
    """A circle from eight off-curve quadratic points (TrueType outer contours run clockwise)."""
    k = r / math.cos(math.pi / 8)
    angles = [math.pi / 4 * i for i in range(8)]
    if clockwise:
        angles.reverse()
    pen.qCurveTo(*[(round(cx + k * math.cos(a)), round(cy + k * math.sin(a))) for a in angles], None)
    pen.closePath()


def cell(code, style):
    pen = TTGlyphPen(None)
    bits = code - 0x2800
    eight = bits >= 0x40
    rows, raised = (ROWS8, RAISED8) if eight else (ROWS6, RAISED)
    for dot in range(1, 9 if eight else 7):
        column, row = DOT_POSITIONS[dot]
        cx, cy = COLUMNS[column], rows[row]
        if bits & (1 << (dot - 1)):
            circle(pen, cx, cy, raised)
        elif style == "rings":
            circle(pen, cx, cy, raised * 0.62)
            circle(pen, cx, cy, raised * 0.62 - 22, clockwise=False)
        else:
            circle(pen, cx, cy, raised * 0.32)
    return pen.glyph()


def build(path, style="dots"):
    names = [".notdef", "space"] + [f"uni{c:04X}" for c in range(0x2800, 0x2900)]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap({0x20: "space", 0xA0: "space", **{c: f"uni{c:04X}" for c in range(0x2800, 0x2900)}})
    empty = TTGlyphPen(None).glyph()
    glyphs = {".notdef": empty, "space": empty, **{f"uni{c:04X}": cell(c, style) for c in range(0x2800, 0x2900)}}
    fb.setupGlyf(glyphs)
    glyf = fb.font["glyf"]
    for n in names:
        glyf[n].recalcBounds(glyf)
    fb.setupHorizontalMetrics({n: (ADVANCE, glyf[n].xMin if glyf[n].numberOfContours else 0) for n in names})
    fb.setupHorizontalHeader(ascent=ASCENT, descent=-DESCENT, lineGap=LINE_GAP)
    fb.setupNameTable({
        "familyName": "Nuridot Braille", "styleName": "Regular", "uniqueFontIdentifier": "Nuridot Braille Regular 1.000",
        "fullName": "Nuridot Braille", "psName": "NuridotBraille-Regular", "version": "Version 1.000",
        "copyright": "Copyright (c) 2026 Semojum", "description": "Braille cells with visible empty dot positions, generated by scripts/build-braille-font.py",
    })
    fb.setupOS2(sTypoAscender=ASCENT, sTypoDescender=-DESCENT, sTypoLineGap=LINE_GAP, usWinAscent=ASCENT, usWinDescent=DESCENT,
                fsType=0, achVendID="SMJM", usFirstCharIndex=0x20, usLastCharIndex=0x28FF)
    fb.setupPost()
    fb.save(path)


if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "dots")
